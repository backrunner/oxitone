//! Small vector glyphs share geometry and weight across the native interface.
use gpui::{prelude::*, *};
#[derive(Clone, Copy)]
pub enum Icon {
    Wave,
    Effect,
    Route,
    Output,
    Input,
    Search,
    Check,
    Curve,
    Draw,
    Paint,
    Select,
    Fit,
    Plus,
    Minus,
    PitchIn,
    PitchOut,
    Maximize,
    Restore,
    Play,
    Pause,
    Stop,
    Loop,
    Left,
    Right,
    Undo,
    Redo,
    Save,
    Code,
    Close,
    Piano,
    Split,
    ChevronDown,
    ChevronUp,
    Magnet,
}
pub fn icon(kind: Icon, color: u32) -> impl IntoElement {
    canvas(
        |_, _, _| {},
        move |at, _, window, _| {
            let lines: &[&[(f32, f32)]] = match kind {
                Icon::Draw => &[
                    &[
                        (3., 10.),
                        (11., 2.),
                        (14., 5.),
                        (6., 13.),
                        (2., 14.),
                        (3., 10.),
                    ],
                    &[(9., 4.), (12., 7.)],
                ],
                Icon::Paint => &[
                    &[(6., 9.), (12., 2.), (14., 4.), (8., 11.)],
                    &[
                        (6., 9.),
                        (3., 10.),
                        (3., 13.),
                        (1., 14.),
                        (6., 14.),
                        (8., 12.),
                        (6., 9.),
                    ],
                ],
                Icon::Select => &[
                    &[(6., 2.), (2., 2.), (2., 6.)],
                    &[(10., 2.), (14., 2.), (14., 6.)],
                    &[(2., 10.), (2., 14.), (6., 14.)],
                    &[(10., 14.), (14., 14.), (14., 10.)],
                ],
                Icon::Fit => &[
                    &[(2., 5.), (2., 2.), (5., 2.)],
                    &[(11., 2.), (14., 2.), (14., 5.)],
                    &[(2., 11.), (2., 14.), (5., 14.)],
                    &[(11., 14.), (14., 14.), (14., 11.)],
                    &[(5., 8.), (11., 8.)],
                ],
                Icon::Plus => &[&[(3., 8.), (13., 8.)], &[(8., 3.), (8., 13.)]],
                Icon::Minus => &[&[(3., 8.), (13., 8.)]],
                Icon::PitchIn => &[
                    &[(2., 3.), (2., 13.), (8., 13.)],
                    &[(2., 6.), (6., 6.)],
                    &[(2., 9.), (6., 9.)],
                    &[(9., 6.), (15., 6.)],
                    &[(12., 3.), (12., 9.)],
                ],
                Icon::PitchOut => &[
                    &[(2., 3.), (2., 13.), (8., 13.)],
                    &[(2., 6.), (6., 6.)],
                    &[(2., 9.), (6., 9.)],
                    &[(9., 6.), (15., 6.)],
                ],
                Icon::Maximize => &[
                    &[(2., 6.), (2., 2.), (6., 2.)],
                    &[(10., 2.), (14., 2.), (14., 6.)],
                    &[(2., 10.), (2., 14.), (6., 14.)],
                    &[(10., 14.), (14., 14.), (14., 10.)],
                ],
                Icon::Restore => &[
                    &[(5., 5.), (5., 1.), (15., 1.), (15., 11.), (11., 11.)],
                    &[(1., 5.), (11., 5.), (11., 15.), (1., 15.), (1., 5.)],
                ],
                Icon::Play => &[&[(4., 2.), (13., 8.), (4., 14.), (4., 2.)]],
                Icon::Pause => &[&[(5., 3.), (5., 13.)], &[(11., 3.), (11., 13.)]],
                Icon::Stop => &[&[(3., 3.), (13., 3.), (13., 13.), (3., 13.), (3., 3.)]],
                Icon::Loop => &[
                    &[(2., 7.), (2., 4.), (13., 4.), (10., 1.)],
                    &[(14., 9.), (14., 12.), (3., 12.), (6., 15.)],
                ],
                Icon::Left => &[&[(10., 3.), (5., 8.), (10., 13.)]],
                Icon::Right => &[&[(6., 3.), (11., 8.), (6., 13.)]],
                Icon::Undo => &[
                    &[(6., 2.), (2., 6.), (6., 10.)],
                    &[(2., 6.), (10., 6.), (13., 8.), (13., 12.), (11., 14.)],
                ],
                Icon::Redo => &[
                    &[(10., 2.), (14., 6.), (10., 10.)],
                    &[(14., 6.), (6., 6.), (3., 8.), (3., 12.), (5., 14.)],
                ],
                Icon::Save => &[
                    &[
                        (2., 2.),
                        (12., 2.),
                        (14., 4.),
                        (14., 14.),
                        (2., 14.),
                        (2., 2.),
                    ],
                    &[(5., 2.), (5., 6.), (10., 6.), (10., 2.)],
                    &[(5., 14.), (5., 10.), (11., 10.), (11., 14.)],
                ],
                Icon::Code => &[
                    &[(5., 4.), (1., 8.), (5., 12.)],
                    &[(11., 4.), (15., 8.), (11., 12.)],
                    &[(9., 2.), (7., 14.)],
                ],
                Icon::Close => &[&[(4., 4.), (12., 12.)], &[(12., 4.), (4., 12.)]],
                Icon::Piano => &[
                    &[(1., 3.), (15., 3.), (15., 13.), (1., 13.), (1., 3.)],
                    &[(5., 3.), (5., 13.)],
                    &[(10., 3.), (10., 13.)],
                    &[(7., 3.), (7., 8.)],
                ],
                Icon::Split => &[
                    &[(2., 2.), (14., 2.), (14., 14.), (2., 14.), (2., 2.)],
                    &[(8., 2.), (8., 14.)],
                ],
                Icon::ChevronDown => &[&[(4., 6.), (8., 10.), (12., 6.)]],
                Icon::ChevronUp => &[&[(4., 10.), (8., 6.), (12., 10.)]],
                Icon::Magnet => &[
                    &[
                        (3., 8.),
                        (3., 4.),
                        (5., 2.),
                        (8., 2.),
                        (11., 2.),
                        (13., 4.),
                        (13., 8.),
                    ],
                    &[(6., 8.), (6., 5.), (10., 5.), (10., 8.)],
                    &[(3., 9.), (5., 13.), (8., 15.), (11., 13.), (13., 9.)],
                ],
                Icon::Search => &[
                    &[(10., 10.), (15., 15.)],
                    &[
                        (11., 6.),
                        (10., 3.),
                        (7., 1.),
                        (3., 2.),
                        (1., 5.),
                        (2., 9.),
                        (5., 11.),
                        (9., 10.),
                        (11., 6.),
                    ],
                ],
                Icon::Check => &[&[(3., 8.), (6., 11.), (13., 4.)]],
                Icon::Curve => &[&[
                    (2., 13.),
                    (4., 12.),
                    (6., 10.),
                    (7., 6.),
                    (9., 3.),
                    (11., 2.),
                    (14., 2.),
                ]],
                Icon::Wave => &[&[
                    (1., 8.),
                    (3., 8.),
                    (5., 3.),
                    (7., 13.),
                    (9., 5.),
                    (11., 11.),
                    (13., 8.),
                    (15., 8.),
                ]],
                Icon::Effect => &[
                    &[(2., 4.), (14., 4.)],
                    &[(2., 8.), (14., 8.)],
                    &[(2., 12.), (14., 12.)],
                    &[(5., 2.), (5., 6.)],
                    &[(11., 6.), (11., 10.)],
                    &[(7., 10.), (7., 14.)],
                ],
                Icon::Route => &[
                    &[(2., 8.), (7., 8.), (7., 3.), (14., 3.)],
                    &[(7., 8.), (7., 13.), (14., 13.)],
                    &[(11., 1.), (14., 3.), (11., 5.)],
                    &[(11., 11.), (14., 13.), (11., 15.)],
                ],
                Icon::Output => &[
                    &[(2., 8.), (12., 8.)],
                    &[(8., 4.), (12., 8.), (8., 12.)],
                    &[(14., 2.), (14., 14.)],
                ],
                Icon::Input => &[
                    &[(3., 2.), (3., 14.)],
                    &[(14., 8.), (5., 8.)],
                    &[(9., 4.), (5., 8.), (9., 12.)],
                ],
            };
            let mut path = PathBuilder::stroke(px(1.35));
            for line in lines {
                for (i, (x, y)) in line.iter().enumerate() {
                    let p = at.origin + point(px(*x), px(*y));
                    if i == 0 {
                        path.move_to(p);
                    } else {
                        path.line_to(p);
                    }
                }
            }
            if let Ok(path) = path.build() {
                window.paint_path(path, rgb(color));
            }
        },
    )
    .size(px(16.))
    .flex_shrink_0()
}
